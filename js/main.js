function initForm() {
  const form = document.getElementById('contactForm');
  const hint = document.getElementById('formHint');
  if (!form) return;

  form.addEventListener('submit', (e) => {
    e.preventDefault();

    const name = form.elements.name;
    const email = form.elements.email;
    const business = form.elements.business;
    const interest = form.elements.interest;
    const message = form.elements.message;

    if (!name.value.trim() || !email.value.trim() || !business.value.trim() || !interest.value) {
      if (hint) {
        hint.textContent = t('contact.error');
        hint.style.color = 'var(--accent-ink)';
      }
      return;
    }

    const subject = encodeURIComponent(
      `${t('contact.mail.subject')} — ${name.value.trim()} (${business.value.trim()})`
    );
    const body = encodeURIComponent(
      `${t('contact.mail.name')}: ${name.value.trim()}\n` +
      `${t('contact.mail.email')}: ${email.value.trim()}\n` +
      `${t('contact.mail.business')}: ${business.value.trim()}\n` +
      `${t('contact.mail.interest')}: ${interest.options[interest.selectedIndex].text}\n\n` +
      `${t('contact.mail.message')}:\n${message.value.trim()}`
    );

    window.location.href = `mailto:hello@simplisite.studio?subject=${subject}&body=${body}`;

    if (hint) {
      hint.textContent = t('contact.success');
      hint.style.color = 'var(--green)';
    }
  });
}

