// ---------- i18n core ----------
const LANG_KEY = 'simplisite-lang';
let currentLang = 'lv';

function readStoredLang() {
  try {
    const stored = localStorage.getItem(LANG_KEY);
    if (stored === 'lv' || stored === 'en') return stored;
  } catch (e) { /* localStorage unavailable */ }
  return 'lv'; // primary language
}

function t(key) {
  const dict = translations[currentLang] || translations.en;
  return dict[key] ?? translations.en[key] ?? key;
}

function applyTranslations() {
  // textContent
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const text = t(el.getAttribute('data-i18n'));
    if (text) el.textContent = text;
  });

  // placeholder attributes
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    const text = t(el.getAttribute('data-i18n-placeholder'));
    if (text) el.setAttribute('placeholder', text);
  });

  // document title + meta description
  document.title = t('doc.title');
  const meta = document.querySelector('meta[name="description"]');
  if (meta) meta.setAttribute('content', t('doc.description'));
}

function updateLangButtons() {
  document.querySelectorAll('.lang-switch__btn').forEach((btn) => {
    const active = btn.getAttribute('data-lang') === currentLang;
    btn.classList.toggle('is-active', active);
    btn.setAttribute('aria-pressed', String(active));
  });
}

function setLang(lang) {
  if (lang !== 'lv' && lang !== 'en') lang = 'lv';
  currentLang = lang;
  try { localStorage.setItem(LANG_KEY, lang); } catch (e) { /* ignore */ }
  document.documentElement.lang = lang;
  applyTranslations();
  updateLangButtons();
}

// ---------- Mobile nav toggle ----------
function initNav() {
  const navToggle = document.getElementById('navToggle');
  const navMobile = document.getElementById('navMobile');
  if (!navToggle || !navMobile) return;

  navToggle.addEventListener('click', () => {
    const isOpen = navMobile.classList.toggle('is-open');
    navToggle.setAttribute('aria-expanded', String(isOpen));
    navMobile.hidden = !isOpen;
  });

  navMobile.querySelectorAll('a').forEach((link) => {
    link.addEventListener('click', () => {
      navMobile.classList.remove('is-open');
      navMobile.hidden = true;
      navToggle.setAttribute('aria-expanded', 'false');
    });
  });
}

